// Helper for formatting currency inside PDFs
const formatAmount = (num: number, currency: string = 'OMR'): string => {
  return `${num.toFixed(3)} ${currency}`;
};

// Helper for drawing clean header bar
const drawPdfHeader = (
  doc: jsPDF,
  title: string,
  subtitle: string,
  docNumber?: string,
  settings?: Partial<SystemSettings>
) => {
  const companyName = settings?.companyName || 'ZUKAIT INTERNATIONAL LLC - WORKSHOP & BODYSHOP';
  const currency = settings?.currency || 'OMR';
  const vatNumber = settings?.vatNumber || 'OM-VAT-9884210';
  const crNumber = settings?.crNumber || 'CR-1049281';
  const address = settings?.address || 'Industrial Area, Muscat, Sultanate of Oman';
  const phone = settings?.phone || '+968 2450 1100';
  const email = settings?.email || 'service@zukait.om';

  // Primary top accent line
  doc.setFillColor(67, 56, 202); // Indigo 700
  doc.rect(0, 0, 210, 5, 'F');

  // Company Branding
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.setTextColor(15, 23, 42); // Slate 900
  doc.text(companyName.toUpperCase(), 14, 18);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.setTextColor(100, 116, 139); // Slate 500
  doc.text(`${address} • Tel: ${phone} • Email: ${email}`, 14, 23);
  doc.text(`CR: ${crNumber} • Tax/VAT Registration: ${vatNumber}`, 14, 27);

  // Document Title & Reference
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.setTextColor(67, 56, 202);
  doc.text(title.toUpperCase(), 196, 18, { align: 'right' });

  if (docNumber) {
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10);
    doc.setTextColor(15, 23, 42);
    doc.text(docNumber, 196, 23, { align: 'right' });
  }

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.setTextColor(100, 116, 139);
  doc.text(subtitle, 196, 27, { align: 'right' });

  // Divider rule
  doc.setDrawColor(226, 232, 240); // Slate 200
  doc.setLineWidth(0.5);
  doc.line(14, 31, 196, 31);
};

// Helper for drawing standard footer on all pages
const drawPdfFooter = (doc: jsPDF) => {
  const pageCount = (doc as any).internal.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setDrawColor(226, 232, 240);
    doc.setLineWidth(0.5);
    doc.line(14, 282, 196, 282);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.setTextColor(148, 163, 184); // Slate 400
    doc.text(
      `Generated by Zukait International LLC Workshop Suite • Certified Tax Compliant`,
      14,
      287
    );
    doc.text(`Page ${i} of ${pageCount}`, 196, 287, { align: 'right' });
  }
};

