// 2. WORKSHOP JOB CARD PROFIT & LOSS REPORT PDF EXPORTER
// ─────────────────────────────────────────────────────────────────────────────
export interface JobCardPnlBreakdown {
  partsCost: number;
  partsRevenue: number;
  laborCost: number;
  laborRevenue: number;
  consumablesCost: number;
  totalJobCost: number;
  totalRevenue: number;
  netProfit: number;
  profitMargin: number;
}

export const exportJobCardPnlReportPDF = (
  jobCards: JobCard[],
  calculatePnl: (jc: JobCard) => JobCardPnlBreakdown,
  settings?: Partial<SystemSettings>
) => {
  const doc = new jsPDF({
    orientation: 'landscape',
    unit: 'mm',
    format: 'a4',
  });

  const currency = settings?.currency || 'OMR';
  const today = new Date().toISOString().split('T')[0];

  // Header
  drawPdfHeader(
    doc,
    'WORKSHOP P&L REPORT',
    `Generated: ${today}`,
    `JOBS: ${jobCards.length}`,
    settings
  );

  // Compute Aggregates
  const aggregates = jobCards.reduce(
    (acc, jc) => {
      const pnl = calculatePnl(jc);
      acc.totalRevenue += pnl.totalRevenue;
      acc.totalPartsCost += pnl.partsCost;
      acc.totalLaborCost += pnl.laborCost;
      acc.totalConsumablesCost += pnl.consumablesCost;
      acc.totalCost += pnl.totalJobCost;
      acc.totalProfit += pnl.netProfit;
      return acc;
    },
    {
      totalRevenue: 0,
      totalPartsCost: 0,
      totalLaborCost: 0,
      totalConsumablesCost: 0,
      totalCost: 0,
      totalProfit: 0,
    }
  );

  const overallMargin =
    aggregates.totalRevenue > 0
      ? +((aggregates.totalProfit / aggregates.totalRevenue) * 100).toFixed(1)
      : 0;

  // Executive Summary KPI Cards (Landscape)
  const kpiBoxWidth = 50;
  const kpiY = 36;
  const kpiGap = 6;
  let startX = 14;

  const kpiItems = [
    { label: 'TOTAL REVENUE', value: formatAmount(aggregates.totalRevenue, currency), color: [16, 185, 129] },
    { label: 'PARTS DIRECT COST', value: formatAmount(aggregates.totalPartsCost, currency), color: [99, 102, 241] },
    { label: 'LABOR WAGE COST', value: formatAmount(aggregates.totalLaborCost, currency), color: [245, 158, 11] },
    { label: 'CONSUMABLES / MAT', value: formatAmount(aggregates.totalConsumablesCost, currency), color: [168, 85, 247] },
    { label: 'NET PROFIT (MARGIN)', value: `${formatAmount(aggregates.totalProfit, currency)} (${overallMargin}%)`, color: aggregates.totalProfit >= 0 ? [16, 185, 129] : [239, 68, 68] },
  ];

  kpiItems.forEach((kpi) => {
    doc.setFillColor(248, 250, 252);
    doc.roundedRect(startX, kpiY, kpiBoxWidth, 18, 1.5, 1.5, 'F');
    doc.setDrawColor(226, 232, 240);
    doc.roundedRect(startX, kpiY, kpiBoxWidth, 18, 1.5, 1.5, 'S');

    // Accent top
    doc.setFillColor(kpi.color[0], kpi.color[1], kpi.color[2]);
    doc.rect(startX, kpiY, kpiBoxWidth, 2, 'F');

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(7);
    doc.setTextColor(100, 116, 139);
    doc.text(kpi.label, startX + 3, kpiY + 7);

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8.5);
    doc.setTextColor(15, 23, 42);
    doc.text(kpi.value, startX + 3, kpiY + 14);

    startX += kpiBoxWidth + kpiGap;
  });

  // Table of Job Cards
  const tableRows = jobCards.map((jc) => {
    const pnl = calculatePnl(jc);
    return [
      jc.jobCardNumber,
      jc.jobType.toUpperCase(),
      jc.customerName,
      jc.vehicleDetails || 'N/A',
      formatAmount(pnl.totalRevenue, currency),
      formatAmount(pnl.partsCost, currency),
      formatAmount(pnl.laborCost, currency),
      formatAmount(pnl.consumablesCost, currency),
      formatAmount(pnl.totalJobCost, currency),
      formatAmount(pnl.netProfit, currency),
      `${pnl.profitMargin}%`,
    ];
  });

  autoTable(doc, {
    startY: 60,
    head: [
      [
        'Job #',
        'Type',
        'Customer',
        'Vehicle',
        'Revenue',
        'Parts Cost',
        'Labor Cost',
        'Consumables',
        'Total Cost',
        'Net Profit',
        'Margin %',
      ],
    ],
    body: tableRows,
    theme: 'grid',
    headStyles: {
      fillColor: [30, 41, 59],
      textColor: [255, 255, 255],
      fontSize: 8,
      fontStyle: 'bold',
      halign: 'center',
    },
    columnStyles: {
      0: { cellWidth: 26, fontStyle: 'bold' },
      1: { cellWidth: 16, halign: 'center' },
      2: { cellWidth: 38 },
      3: { cellWidth: 42 },
      4: { cellWidth: 23, halign: 'right' },
      5: { cellWidth: 22, halign: 'right' },
      6: { cellWidth: 22, halign: 'right' },
      7: { cellWidth: 22, halign: 'right' },
      8: { cellWidth: 23, halign: 'right' },
      9: { cellWidth: 23, halign: 'right', fontStyle: 'bold' },
      10: { cellWidth: 18, halign: 'center' },
    },
    styles: {
      fontSize: 7.5,
      cellPadding: 2.2,
      textColor: [51, 65, 85],
    },
    alternateRowStyles: {
      fillColor: [248, 250, 252],
    },
  });

  // Footer
  drawPdfFooter(doc);

  // Download
  doc.save(`Workshop_JobCard_PnL_Report_${today}.pdf`);
};

